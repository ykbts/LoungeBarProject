CREATE SCHEMA lounge;

-- Enumeration for PAYMENT METHOD
CREATE TYPE lounge.Payment AS ENUM ('CASH', 'BANCOMAT', 'DEBIT_CARD');

-- Enumeration for STATE of the Order
CREATE TYPE lounge.OrdersState AS ENUM ('PENDING', 'PAID', 'CANCELED');

-- Enumeration for Role of the User
CREATE TYPE lounge.UserRole AS ENUM ('WAITER', 'CUSTOMER', 'ADMIN');

-- Enumeration for Type of the Supply
CREATE TYPE lounge.SupplyType AS ENUM ('DISCRETE', 'BOTTLE_0_7L', 'BOTTLE_1L');

-- ##########################################################
--      tables creation
-- ##########################################################

-- Supply table
CREATE TABLE lounge.Supply (
    name VARCHAR(50),
    units_available SMALLINT
            DEFAULT 0
            NOT NULL
            CHECK (units_available >= 0),
    type lounge.SupplyType NOT NULL,
    PRIMARY KEY (name)
);

-- Drink table
CREATE TABLE lounge.Drink (
    name VARCHAR(50),
    price DECIMAL(5,2)
            DEFAULT 0.00
            NOT NULL
            CHECK (price >= 0),
    is_alcoholic BOOLEAN NOT NULL,
    PRIMARY KEY (name)
);

-- Composition table
CREATE TABLE lounge.Composition (
    drink_name VARCHAR(50),
    supply_name VARCHAR(50),
    amount INT CHECK (amount > 0),
    PRIMARY KEY (drink_name, supply_name),
    FOREIGN KEY (drink_name) REFERENCES lounge.Drink(name),
    FOREIGN KEY (supply_name) REFERENCES lounge.Supply(name)
);

-- Tables table
CREATE TABLE lounge.Tables (
    number SMALLINT,
    capacity SMALLINT
            DEFAULT 1
            NOT NULL
            CHECK (capacity > 0),
    is_available
            BOOLEAN
            DEFAULT TRUE
            NOT NULL,
    PRIMARY KEY (number)
);

-- User table
CREATE TABLE lounge.User (
     username VARCHAR(50) UNIQUE NOT NULL,
     password VARCHAR(255) NOT NULL,
     name VARCHAR(50) NOT NULL,
     surname VARCHAR(50),
     phone VARCHAR(20),
     role lounge.UserRole NOT NULL,
     PRIMARY KEY (username),
     CONSTRAINT valid_username CHECK (username ~ '^[a-zA-Z][a-zA-Z0-9_.]{2,29}$'),
     CONSTRAINT valid_phone CHECK (phone ~ '^[0-9+() -]+$')
);

-- Orders table
CREATE TABLE lounge.Orders (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    date_time TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,
    status lounge.OrdersState
            DEFAULT 'PENDING'
            NOT NULL,
    pay_method lounge.Payment,
    user_waiterID VARCHAR(20),
    tableID SMALLINT,
    PRIMARY KEY (id),
    FOREIGN KEY (user_waiterID) REFERENCES lounge.User(username),
    FOREIGN KEY (tableID) REFERENCES lounge.Tables(number),
    CONSTRAINT payment_check CHECK (
        (status = 'PAID' AND pay_method IS NOT NULL) OR
        (status <> 'PAID' AND pay_method IS NULL)
    )
);

-- OrderItem table
CREATE TABLE lounge.OrderItem (
    drink_name VARCHAR(50),
    orderID INT,
    quantity SMALLINT
            NOT NULL
            CHECK (quantity > 0),
    PRIMARY KEY (drink_name, orderID),
    FOREIGN KEY (drink_name) REFERENCES lounge.Drink(name),
    FOREIGN KEY (orderID) REFERENCES lounge.Orders(id)
);

-- Reservation table
CREATE TABLE lounge.Reservation (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    n_people SMALLINT
            NOT NULL
            CHECK (n_people > 0),
    user_customerID VARCHAR(20),
    tableNumber SMALLINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (tableNumber) REFERENCES lounge.Tables(number),
    FOREIGN KEY (user_customerID) REFERENCES lounge.User(username),
    CONSTRAINT reservation_duration_check CHECK (
        (end_time - start_time) BETWEEN INTERVAL '1 hour' AND INTERVAL '4 hours'
        )
);

-- Review table
CREATE TABLE lounge.Review (
    user_waiterID VARCHAR(20),
    user_customerID VARCHAR(20),
    score SMALLINT
            NOT NULL
            CHECK (score >= 1 AND score <= 5),
    comment VARCHAR(500),
    PRIMARY KEY (user_waiterID, user_customerID),
    FOREIGN KEY (user_waiterID) REFERENCES lounge.User(username),
    FOREIGN KEY (user_customerID) REFERENCES lounge.User(username)
);

-- Shift table
CREATE TABLE lounge.Shift (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    CONSTRAINT shift_duration_limit CHECK (
        (end_time - start_time) BETWEEN INTERVAL '1 hour' AND INTERVAL '8 hours'
        ),
    PRIMARY KEY (id)
);


-- Work table
CREATE TABLE lounge.Work (
    user_waiterID VARCHAR(50),
    shiftID INT,
    PRIMARY KEY (user_waiterID, shiftID),
    FOREIGN KEY (user_waiterID) REFERENCES lounge.User(username),
    FOREIGN KEY (shiftID) REFERENCES lounge.Shift(id)
);