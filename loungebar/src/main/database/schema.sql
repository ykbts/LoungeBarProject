-- Database: LoungeBar

-- Enumeration for PAYMENT METHOD
CREATE TYPE Payment AS ENUM ('CASH', 'BANCOMAT', 'DEBIT CARD');

-- Enumeration for STATE of the Order
CREATE TYPE OrdersState AS ENUM ('PENDING', 'PAID', 'CANCELED');

-- ##########################################################
--      tables creation
-- ##########################################################

-- Supply table
CREATE TABLE Supply (
    name VARCHAR(50),
    units_available SMALLINT 
            DEFAULT 0 
            NOT NULL 
            CHECK (units_available >= 0),
    PRIMARY KEY (name)
);

-- Drink table
CREATE TABLE Drink (
    name VARCHAR(50),
    price DECIMAL(5,2) 
            DEFAULT 0.00 
            NOT NULL 
            CHECK (price >= 0),
    is_alcoholic BOOLEAN NOT NULL,
    PRIMARY KEY (name)
);

-- Composition table
CREATE TABLE Composition (
    drink_name VARCHAR(50),
    supply_name VARCHAR(50),
    amount INT CHECK (amount > 0),
    PRIMARY KEY (drink_name, supply_name),
    FOREIGN KEY (drink_name) REFERENCES Drink(name),
    FOREIGN KEY (supply_name) REFERENCES Supply(name)
);

-- Tables table
CREATE TABLE Tables (
    number SMALLINT,
    capacity SMALLINT 
            DEFAULT 1
            NOT NULL
            CHECK (capacity > 0),
    is_available 
            BOOLEAN 
            DEFAULT TRUE 
            NOT NULL,
    PRIMARY KEY (number)
);

-- Waiter table
CREATE TABLE Waiter (
    phone VARCHAR(20),
    name VARCHAR(50) NOT NULL,
    surname VARCHAR(50),
    PRIMARY KEY (phone),
    CONSTRAINT valid_phone CHECK (phone ~ '^[0-9+() -]+$')
);

-- Orders table
CREATE TABLE Orders (
    id INT GENERATED BY DEFAULT AS IDENTITY, 
    date_time TIMESTAMP NOT NULL,
    status OrdersState 
            DEFAULT 'PENDING'
            NOT NULL,
    pay_method Payment,
    waiterID VARCHAR(20),
    tableID SMALLINT,
    PRIMARY KEY (id),
    FOREIGN KEY (waiterID) REFERENCES Waiter(phone),
    FOREIGN KEY (tableID) REFERENCES Tables(number),
    CONSTRAINT payment_check CHECK (
        (status = 'PAID' AND pay_method IS NOT NULL) OR 
        (status <> 'PAID' AND pay_method IS NULL)
    )
);

-- OrderItem table
CREATE TABLE OrderItem (
    drink_name VARCHAR(50),
    orderID INT,
    quantity SMALLINT 
            NOT NULL 
            CHECK (quantity > 0),
    PRIMARY KEY (drink_name, orderID),
    FOREIGN KEY (drink_name) REFERENCES Drink(name),
    FOREIGN KEY (orderID) REFERENCES Orders(id)
);

-- Customer table
CREATE TABLE Customer (
    phone VARCHAR(20),
    name VARCHAR(50) NOT NULL,
    surname VARCHAR(50) NOT NULL,
    PRIMARY KEY (phone),
    CONSTRAINT valid_cust_phone CHECK (phone ~ '^[0-9+() -]+$')
);

-- Reservation table
CREATE TABLE Reservation (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    reservation_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    n_people SMALLINT 
            NOT NULL 
            CHECK (n_people > 0),
    tableNumber SMALLINT,
    customerID VARCHAR(20),
    PRIMARY KEY (id),
    FOREIGN KEY (tableNumber) REFERENCES Tables(number),
    FOREIGN KEY (customerID) REFERENCES Customer(phone),
    CONSTRAINT reservation_duration_check CHECK (
        EXTRACT(EPOCH FROM (end_time - start_time + CASE WHEN end_time < start_time THEN INTERVAL '1 day' ELSE INTERVAL '0' END)) 
        BETWEEN 3600 AND 14400
    )
);

-- Review table
CREATE TABLE Review (
    waiterID VARCHAR(20),
    customerID VARCHAR(20),
    score SMALLINT 
            NOT NULL 
            CHECK (score >= 1 AND score <= 5),
    comment VARCHAR(500),
    PRIMARY KEY (waiterID, customerID),
    FOREIGN KEY (waiterID) REFERENCES Waiter(phone),
    FOREIGN KEY (customerID) REFERENCES Customer(phone)
);

-- Shift table
CREATE TABLE Shift (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    shift_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    CONSTRAINT shift_duration_check CHECK (
        EXTRACT(EPOCH FROM (end_time - start_time + CASE WHEN end_time < start_time THEN INTERVAL '1 day' ELSE INTERVAL '0' END)) 
        BETWEEN 3600 AND 28800
    ),
    PRIMARY KEY (id)
);

-- Work table
CREATE TABLE Work (
    waiterID VARCHAR(20),
    shiftID INT,
    PRIMARY KEY (waiterID, shiftID),
    FOREIGN KEY (waiterID) REFERENCES Waiter(phone),
    FOREIGN KEY (shiftID) REFERENCES Shift(id)
);